export function buildTemplates(): Template[] {
  return SPECS.map((spec) => {
    const graph = instantiateGraph(spec.graph, `${spec.id}_`)
    return {
      id: spec.id,
      name: spec.name,
      description: spec.description,
      longDescription: spec.longDescription,
      category: spec.category,
      icon: spec.icon,
      tags: spec.tags,
      usedBy: spec.usedBy,
      rating: spec.rating,
      authorId: spec.authorId,
      featured: spec.featured,
      estimatedSetupMin: spec.setup,
      nodes: graph.nodes,
      edges: graph.edges,
      integrations: spec.integrations,
      createdAt: daysAgo(spec.ageDays),
    } satisfies Template
  })
}

