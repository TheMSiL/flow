const CHANGE_MESSAGES = [
  'Raised the scoring threshold',
  'Added a Slack notification',
  'Switched to the pro model',
  'Fixed the missing NO branch',
  'Renamed nodes for clarity',
  'Reduced the wait to 1 day',
  'Connected the new mailbox',
  'Added error handling',
  'Tuned the AI prompt',
  'Removed the legacy webhook',
]

function buildVersions(spec: Spec, nodeCount: number, edgeCount: number): WorkflowVersion[] {
  const rng = createRng(SEED + spec.id.charCodeAt(3) * 977)
  const versions: WorkflowVersion[] = []
  for (let v = spec.version; v >= 1; v--) {
    const isLatest = v === spec.version
    versions.push({
      id: `${spec.id}_v${v}`,
      version: v,
      createdAt: daysAgo(spec.createdDaysAgo - (v - 1) * Math.max(1, Math.floor(spec.createdDaysAgo / (spec.version + 1)))),
      authorId: spec.ownerId,
      status: isLatest && spec.status === 'draft' ? 'draft' : 'published',
      message: pick(rng, CHANGE_MESSAGES),
      changes: [pick(rng, CHANGE_MESSAGES), pick(rng, CHANGE_MESSAGES)].filter(
        (value, index, arr) => arr.indexOf(value) === index,
      ),
      nodeCount: Math.max(2, nodeCount - (spec.version - v)),
      edgeCount: Math.max(1, edgeCount - (spec.version - v)),
    })
  }
  return versions
}

export function buildWorkflows(): Workflow[] {
  return SPECS.map((spec) => {
    const graph = instantiateGraph(spec.graph, `${spec.id}_`)
    return {
      id: spec.id,
      workspaceId: spec.workspaceId,
      name: spec.name,
      description: spec.description,
      status: spec.status,
      nodes: graph.nodes,
      edges: graph.edges,
      ownerId: spec.ownerId,
      environment: spec.environment,
      version: spec.version,
      tags: spec.tags,
      stats: {
        runs: 0,
        successRate: 100,
        avgDurationMs: 0,
        lastRunAt: null,
        lastRunStatus: null,
      },
      versions: buildVersions(spec, graph.nodes.length, graph.edges.length),
      viewport: undefined,
      createdAt: daysAgo(spec.createdDaysAgo),
      updatedAt: hoursAgo(spec.updatedHoursAgo),
    } satisfies Workflow
  })
}

